"""Compare a generated SWIG Python module with its public type declarations."""

from __future__ import annotations

import argparse
import ast
from collections import defaultdict
from pathlib import Path

DEFAULT_STUB = (
    Path(__file__).resolve().parents[2] / "wrappers/Python/roadrunner/roadrunner.pyi"
)


def declarations(body: list[ast.stmt]) -> dict[str, list[ast.stmt]]:
    """Keep each declaration of a name, including overloads and property setters."""
    result: dict[str, list[ast.stmt]] = defaultdict(list)
    for node in body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef)):
            result[node.name].append(node)
        elif isinstance(node, (ast.AnnAssign, ast.Assign)):
            targets = [node.target] if isinstance(node, ast.AnnAssign) else node.targets
            for target in targets:
                if isinstance(target, ast.Name):
                    result[target.id].append(node)
        elif isinstance(node, ast.ImportFrom) and node.level:
            for alias in node.names:
                result[alias.asname or alias.name].append(node)
    return result


def class_members(
    cls: ast.ClassDef, classes: dict[str, ast.ClassDef]
) -> dict[str, list[ast.stmt]]:
    members: dict[str, list[ast.stmt]] = {}
    for base in cls.bases:
        if isinstance(base, ast.Subscript):
            base = base.value
        if isinstance(base, ast.Name) and base.id in classes:
            members.update(class_members(classes[base.id], classes))
    members.update(declarations(cls.body))
    return members


def annotation_errors(name: str, func: ast.FunctionDef, method: bool) -> list[str]:
    errors = []
    if func.returns is None:
        errors.append(f"{name} has no return annotation")
    args = func.args
    positional = [*args.posonlyargs, *args.args]
    if method and positional and positional[0].arg in {"self", "cls"}:
        positional = positional[1:]
    for arg in [*positional, *args.kwonlyargs, args.vararg, args.kwarg]:
        if arg is not None and arg.annotation is None:
            errors.append(f"{name} has no annotation for {arg.arg}")
    return errors


def check_scope(
    wrapper: dict[str, list[ast.stmt]],
    stub: dict[str, list[ast.stmt]],
    classes: dict[str, ast.ClassDef],
    owner: str = "",
) -> list[str]:
    errors = []
    for name, generated in wrapper.items():
        original = generated[-1]
        # Include generated Python protocol methods. SWIG's private bookkeeping
        # assignments (e.g. __swig_destroy__) are implementation details.
        protocol = (
            owner
            and isinstance(original, ast.FunctionDef)
            and name.startswith("__")
            and name.endswith("__")
        )
        if name.startswith("_") and not protocol:
            continue
        qualified = f"{owner}.{name}" if owner else name
        candidates = stub.get(name, [])
        if not candidates:
            errors.append(f"{qualified} is missing")
        elif isinstance(original, ast.ClassDef):
            if name in classes:
                errors.extend(
                    check_scope(
                        declarations(original.body),
                        class_members(classes[name], classes),
                        classes,
                        name,
                    )
                )
            else:
                errors.append(f"{qualified} must be declared as a class")
        else:
            for candidate in candidates:
                if isinstance(candidate, ast.FunctionDef):
                    errors.extend(annotation_errors(qualified, candidate, bool(owner)))
                elif isinstance(original, ast.FunctionDef):
                    errors.append(
                        f"{qualified} must be declared as a method or function"
                    )
                elif not isinstance(candidate, (ast.AnnAssign, ast.ImportFrom)):
                    errors.append(f"{qualified} has no annotation")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wrapper", type=Path, help="roadrunner.py generated by SWIG")
    parser.add_argument("stub", type=Path, nargs="?", default=DEFAULT_STUB)
    parser.add_argument(
        "--package-stub", type=Path, help="check re-exports in __init__.pyi"
    )
    args = parser.parse_args()
    wrapper = ast.parse(
        args.wrapper.read_text(encoding="utf-8"), filename=str(args.wrapper)
    )
    stub = ast.parse(args.stub.read_text(encoding="utf-8"), filename=str(args.stub))
    classes = {node.name: node for node in stub.body if isinstance(node, ast.ClassDef)}
    api = declarations(wrapper.body)
    errors = check_scope(api, declarations(stub.body), classes)
    if args.package_stub:
        package = ast.parse(
            args.package_stub.read_text(encoding="utf-8"),
            filename=str(args.package_stub),
        )
        exports = {
            alias.name
            for node in package.body
            if isinstance(node, ast.ImportFrom)
            and node.level == 1
            and node.module == "roadrunner"
            for alias in node.names
            if alias.asname == alias.name or alias.name == "*"
        }
        if "*" not in exports:
            errors.extend(
                f"{name} is missing from package exports"
                for name in api
                if not name.startswith("_") and name not in exports
            )
    for error in errors:
        print(error)
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
